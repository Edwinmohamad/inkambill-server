'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const network=require('../routes/network');
const routes=network.stack.filter(layer=>layer.route).map(layer=>layer.route);
for(const endpoint of ['/api/smart-sync-plan','/smart-sync','/secrets/:secretId/sync','/api/sync-history','/:customerId/isolate','/:customerId/unisolate'])assert(routes.some(route=>route.path===endpoint),endpoint);
const redirect=routes.find(route=>Array.isArray(route.path)&&route.path.includes('/monitor'));
assert(redirect,'old monitoring bookmark must redirect to PPPoE');
for(const endpoint of ['/api/traffic','/api/telemetry/capture','/api/infrastructure/live','/api/backups','/api/config-drift'])assert(!routes.some(route=>route.path===endpoint),endpoint);
const app=fs.readFileSync('app.js','utf8');
assert(!app.includes('nmsPoller.start()')&&!app.includes('captureAllNmsTelemetry('));
assert(!app.includes('runExperienceProbes(')&&!app.includes('evaluateNetworkIncidents('));
assert(app.includes('await runAutoIsolation()')&&app.includes('await scanLowStock()'));
assert(!fs.existsSync('views/nms/dashboard.ejs')&&!fs.existsSync('services/nms/poller.js'));
console.log('PASS network consolidation: compatibility mapping routes retained, monitoring routes/jobs removed, billing jobs retained.');
